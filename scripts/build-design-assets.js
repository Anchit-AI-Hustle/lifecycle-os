#!/usr/bin/env node
'use strict';
/**
 * build-design-assets.js - the Lifecycle OS icon set and illustrations, from ONE
 * source each.
 * ---------------------------------------------------------------------------
 *   node scripts/build-design-assets.js           write every file
 *   node scripts/build-design-assets.js --check   exit 1 if a committed file drifted
 *
 * Sources: design/lifecycle-os/icons.json and design/lifecycle-os/illustrations.json.
 * Outputs (committed, served as static files):
 *   assets/lifecycle-os/icons.svg                 <symbol id="i-<name>"> sprite
 *   assets/lifecycle-os/icons/<name>.svg          one standalone file per icon
 *   assets/lifecycle-os/illustrations.svg         <symbol id="ill-<name>"> sprite
 *   assets/lifecycle-os/illustrations/<name>.svg  one standalone file per illustration
 *
 * WHY A SPRITE AND NOT AN <img>. An icon drawn in currentColor takes the colour
 * of the text beside it only when it is part of the document: through <use>, an
 * inline <svg>, or a CSS mask. As an <img> it renders black whatever the page
 * says. The sprite's <symbol>s carry NO stroke or fill attributes, so the
 * .vh-icon rule in theme.css (stroke: currentColor; stroke-width:
 * var(--vh-icon-stroke)) reaches every path; the standalone files carry the
 * attributes themselves so they also render on their own.
 *
 * Illustrations read --vh-ill-* tokens, and custom properties inherit into a
 * <use> shadow tree, so an empty state drawn from the sprite takes the active
 * brand's colours; the fallback inside each var() is a neutral grey for the
 * standalone file.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ICONS = JSON.parse(fs.readFileSync(path.join(ROOT, 'design', 'lifecycle-os', 'icons.json'), 'utf8'));
const ILLS = JSON.parse(fs.readFileSync(path.join(ROOT, 'design', 'lifecycle-os', 'illustrations.json'), 'utf8'));
const OUT = path.join(ROOT, 'assets', 'lifecycle-os');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const STROKE = 'fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"';

function iconFile(icon) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ICONS.viewBox}" width="24" height="24" ${STROKE} role="img" aria-label="${esc(icon.name)}">`
    + `<title>${esc(icon.name)}</title>${icon.body}</svg>\n`;
}

function illustrationFile(ill) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ILLS.viewBox}" width="128" height="96" role="img" aria-label="${esc(ill.title)}">`
    + `<title>${esc(ill.title)}</title>${ill.body}</svg>\n`;
}

function sprite(kind) {
  const head = '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">\n';
  const note = kind === 'icons'
    ? '<!-- Lifecycle OS UI icons. Generated by scripts/build-design-assets.js from design/lifecycle-os/icons.json; do not edit by hand. Use: <svg class="vh-icon" aria-hidden="true"><use href="/assets/lifecycle-os/icons.svg#i-NAME"/></svg> -->\n'
    : '<!-- Lifecycle OS illustrations. Generated by scripts/build-design-assets.js from design/lifecycle-os/illustrations.json; do not edit by hand. Use: <svg class="vh-empty-art" viewBox="0 0 128 96" aria-hidden="true"><use href="/assets/lifecycle-os/illustrations.svg#ill-NAME"/></svg> -->\n';
  const body = kind === 'icons'
    ? ICONS.icons.map((i) => `<symbol id="i-${i.name}" viewBox="${ICONS.viewBox}">${i.body}</symbol>`).join('\n')
    : ILLS.illustrations.map((i) => `<symbol id="ill-${i.name}" viewBox="${ILLS.viewBox}">${i.body}</symbol>`).join('\n');
  return head + note + body + '\n</svg>\n';
}

/* The icon and illustration grids on /design-system, generated so the page
   cannot list a different set from the sprite it draws them from. */
const PAGE = 'design-system.html';
function pageGrids(src) {
  const icons = ICONS.icons.map((i) => `      <div class="ds-icon" title="${esc(i.use)}"><svg class="vh-icon vh-icon-lg" aria-hidden="true"><use href="/assets/lifecycle-os/icons.svg#i-${i.name}"/></svg><span>${i.name}</span></div>`).join('\n');
  const ills = ILLS.illustrations.map((i) => `      <figure class="ds-ill" title="${esc(i.use)}"><svg class="vh-empty-art" viewBox="${ILLS.viewBox}" aria-hidden="true"><use href="/assets/lifecycle-os/illustrations.svg#ill-${i.name}"/></svg><span>${i.name}: ${esc(i.title)}</span></figure>`).join('\n');
  const put = (text, begin, end, body) => {
    const bi = text.indexOf(begin), ei = text.indexOf(end);
    if (bi < 0 || ei < 0) throw new Error(`${PAGE} lost its ${begin} markers`);
    return text.slice(0, bi + begin.length) + '\n' + body + '\n' + text.slice(ei);
  };
  let out = put(src, '<!-- >>> DS:icons generated by scripts/build-design-assets.js -->', '<!-- <<< DS:icons -->', icons);
  out = put(out, '<!-- >>> DS:illustrations generated by scripts/build-design-assets.js -->', '<!-- <<< DS:illustrations -->', ills);
  return out;
}

/** Every file this script owns, path -> contents. */
function outputs() {
  const out = {};
  out[PAGE] = pageGrids(fs.readFileSync(path.join(ROOT, PAGE), 'utf8'));
  out['assets/lifecycle-os/icons.svg'] = sprite('icons');
  for (const i of ICONS.icons) out[`assets/lifecycle-os/icons/${i.name}.svg`] = iconFile(i);
  out['assets/lifecycle-os/illustrations.svg'] = sprite('illustrations');
  for (const i of ILLS.illustrations) out[`assets/lifecycle-os/illustrations/${i.name}.svg`] = illustrationFile(i);
  return out;
}

module.exports = { ICONS, ILLS, outputs, iconFile, illustrationFile, sprite, OUT };

if (require.main === module) {
  const CHECK = process.argv.includes('--check');
  const files = outputs();
  let drift = 0;
  for (const [rel, body] of Object.entries(files)) {
    const abs = path.join(ROOT, rel);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (cur === body) continue;
    if (CHECK) { console.error(`DRIFTED ${rel}`); drift++; continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, body);
    console.log(`wrote   ${rel}`);
  }
  if (CHECK && drift) { console.error(`\n${drift} design asset(s) out of sync: run node scripts/build-design-assets.js`); process.exit(1); }
  console.log(`${ICONS.icons.length} icons, ${ILLS.illustrations.length} illustrations${CHECK ? ' in sync' : ''}.`);
}
